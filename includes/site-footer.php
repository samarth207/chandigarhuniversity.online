    // Fallback accordion functionality for mobile if Bootstrap is not available

    (function() {

        if (typeof jQuery !== 'undefined') {

            jQuery(document).ready(function($) {

                // Check if Bootstrap accordion is not working, use custom implementation

                if (typeof bootstrap === 'undefined') {

                    $('.footer-program-accordion .accordion-button').on('click', function(e) {

                        e.preventDefault();

                        var $button = $(this);

                        var $collapse = $($button.data('bs-target') || $button.attr('data-bs-target'));

                        var isExpanded = $button.attr('aria-expanded') === 'true';

                        

                        // Close all other accordions

                        $('.footer-program-accordion .accordion-collapse').not($collapse).slideUp(300);

                        $('.footer-program-accordion .accordion-button').not($button).addClass('collapsed').attr('aria-expanded', 'false');

                        

                        // Toggle current accordion

                        if (isExpanded) {

                            $collapse.slideUp(300);

                            $button.addClass('collapsed').attr('aria-expanded', 'false');

                        } else {

                            $collapse.slideDown(300);

                            $button.removeClass('collapsed').attr('aria-expanded', 'true');

                        }

                    });

                }

            });

        }

    })();

